def main(kind):
    done=build(kind);queue=read(OUT/kind/'review_queue.json')
    # Refresh occurrence/evidence provenance from the final queue, retaining decisions.
    fresh={r['review_id']:r for r in queue}
    fields=['kind','verdict','reference_ids','partial_reference_ids','A_grounded','source_status','rationale','canonical_id',
            'conjunctive_atoms','reviewer','earliest_grounded_prefix','grounded_reference_ids']
    done=[{**fresh[r['review_id']],**{k:r[k] for k in fields if k in r}} for r in done]
    by={r['review_id']:r for r in done}
    assert len(by)==len(done)
    save(OUT/kind/'review_draft.json',done)
    missing=[r for r in queue if r['review_id'] not in by]
    save(OUT/kind/'review_remaining.json',missing)
    if not missing:
        assert set(by)=={r['review_id'] for r in queue}
        save(OUT/kind/('assistant_semantic_review.json' if kind=='isc4' else 'semantic_review.json'),done)
    print({'kind':kind,'reviewed':len(done),'queued':len(queue),'remaining':len(missing)})

